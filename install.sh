#!/usr/bin/env bash
# Installs this project and an `opencode-shim` command you can run from any repo.
#
#   ./install.sh                  install; the command goes in ~/.local/bin
#   ./install.sh --bin-dir DIR    put the command somewhere else
#   ./install.sh --uninstall      remove the command
#
# `opencode-shim` runs the opencode bundled with this repo, configured to use the
# shim, in whatever folder you call it from. If the shim is not running yet, it
# starts it in the background first. Any arguments are passed on to opencode.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="$HOME/.local/bin"
NAME="opencode-shim"
MARKER="# opencode-shim launcher, generated by install.sh"
UNINSTALL=0

while [ $# -gt 0 ]; do
  case "$1" in
    --bin-dir) BIN_DIR="${2:?--bin-dir needs a directory}"; shift 2 ;;
    --uninstall) UNINSTALL=1; shift ;;
    -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "install.sh: unknown option: $1 (try --help)" >&2; exit 1 ;;
  esac
done

LAUNCHER="$BIN_DIR/$NAME"

# Never overwrite or delete a file of the same name that this script did not write.
if [ -e "$LAUNCHER" ] && ! grep -qF "$MARKER" "$LAUNCHER"; then
  echo "install.sh: $LAUNCHER already exists and was not created by this script. Leaving it alone." >&2
  exit 1
fi

if [ "$UNINSTALL" = 1 ]; then
  rm -f "$LAUNCHER"
  echo "Removed $LAUNCHER"
  exit 0
fi

if ! command -v node >/dev/null 2>&1 || ! command -v npm >/dev/null 2>&1; then
  echo "install.sh: Node.js 22 or newer, with npm, is required: https://nodejs.org" >&2
  exit 1
fi
if [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 22 ]; then
  echo "install.sh: Node.js 22 or newer is required (found $(node --version))." >&2
  exit 1
fi
if ! command -v curl >/dev/null 2>&1; then
  echo "install.sh: curl is required (the command uses it to check whether the shim is running)." >&2
  exit 1
fi

echo "==> Installing dependencies and building"
(cd "$REPO" && npm install --no-audit --no-fund)

echo "==> Writing $LAUNCHER"
mkdir -p "$BIN_DIR"
{
  echo '#!/usr/bin/env bash'
  echo "$MARKER"
  echo '# Runs the educational opencode, wired to the shim, in the current folder.'
  echo '# If you move the repo, run its install.sh again.'
  echo 'set -euo pipefail'
  printf 'REPO=%q\n' "$REPO"
  cat <<'EOF'

PORT="${COPILOT_SHIM_PORT:-8787}"
OPENCODE="$REPO/node_modules/.bin/opencode"
LOG="$REPO/.scratch/shim-background.log"

if [ ! -x "$OPENCODE" ] || [ ! -f "$REPO/dist/shim-server.js" ]; then
  echo "opencode-shim: $REPO is not built. Run $REPO/install.sh" >&2
  exit 1
fi

# Any HTTP response at all means something is listening; connection refused means not.
shim_up() { curl -s -o /dev/null --max-time 1 "http://127.0.0.1:$PORT/"; }

if ! shim_up; then
  mkdir -p "$REPO/.scratch"
  # Started from the repo so traces land in its .scratch/shim-log/. Background
  # starts always use the manual (copy and paste) transport.
  (cd "$REPO" && COPILOT_TRANSPORT=manual nohup node dist/shim-server.js >>"$LOG" 2>&1 &)
  for _ in $(seq 1 50); do
    shim_up && break
    sleep 0.2
  done
  if ! shim_up; then
    echo "opencode-shim: the shim did not start. See $LOG" >&2
    exit 1
  fi
  echo "opencode-shim: started the shim in the background (log: $LOG; stop it with: pkill -f shim-server)" >&2
fi

export OPENCODE_CONFIG="$REPO/opencode.json"
exec "$OPENCODE" "$@"
EOF
} >"$LAUNCHER"
chmod +x "$LAUNCHER"

echo
echo "Installed. From any repo, run:"
echo "  $NAME                    interactive UI"
echo "  $NAME run \"your task\"    a single task"

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *)
    echo
    echo "$BIN_DIR is not on your PATH. Add this line to ~/.zshrc or ~/.bashrc, then open a new terminal:"
    echo "  export PATH=\"$BIN_DIR:\$PATH\""
    ;;
esac
